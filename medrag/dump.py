"""Human-readable structure dump of the Knowledge Base (headings and counts
only, no KB content, because the KB documents are kept out of git)."""
from __future__ import annotations

from .models import KBDocument

HEADER = """\
# Knowledge Base structure

Generated by `python -m medrag dump --out docs/kb-structure.md`; do not edit by hand.
Each line is `disease › drug class — product rows, other rows` (table header
rows excluded). Product rows are Trade Name / Active Ingredient rows; other
rows are side effects, OTC classification and anything the header does not
identify. Only headings and counts appear here; the KB content itself is not
committed.
Markers: `[otc]` an OTC vs Prescription block, `[overview]` text under a
disease heading before its first drug class. A bracketed label such as
`[table with no heading in source]` is descriptive, not from the source: that
block has no heading of its own and cites its disease title.
"""


def render_dump(documents: tuple[KBDocument, ...]) -> str:
    out = [HEADER]
    total_sections = total_products = total_other = 0
    for doc in documents:
        products = sum(len(s.product_rows) for s in doc.sections)
        other = sum(len(s.other_rows) for s in doc.sections)
        total_sections += len(doc.sections)
        total_products += products
        total_other += other
        out.append(f"## {doc.kb_id}: {'; '.join(doc.diseases)}\n")
        for s in doc.sections:
            marks = {"overview": " [overview]", "otc": " [otc]"}.get(s.kind, "")
            out.append(
                f"- {s.path} — {len(s.product_rows)} product, {len(s.other_rows)} other{marks}"
            )
        out.append(
            f"\n{len(doc.sections)} sections, {products} product rows, {other} other rows\n"
        )
    out.append(
        f"Total: {total_sections} sections, {total_products} product rows, "
        f"{total_other} other rows\n"
    )
    return "\n".join(out)
