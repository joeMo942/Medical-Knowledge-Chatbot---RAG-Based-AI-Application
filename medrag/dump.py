"""Human-readable structure dump of the Knowledge Base (headings and counts
only, no KB content, because the KB documents are kept out of git)."""
from __future__ import annotations

from .models import KBDocument

HEADER = """\
# Knowledge Base structure

Generated by `python -m medrag dump --out docs/kb-structure.md`; do not edit by hand.
Each line is `disease › drug class — data rows` (table header rows excluded).
Only headings and counts appear here; the KB content itself is not committed.
Markers: `[otc]` an OTC vs Prescription block, `[overview]` text under a
disease heading before its first drug class, `[no heading in source]` a block
whose name was supplied by the splitter because the document has none.
"""


def render_dump(documents: tuple[KBDocument, ...]) -> str:
    out = [HEADER]
    total_sections = total_rows = 0
    for doc in documents:
        rows = sum(s.row_count for s in doc.sections)
        total_sections += len(doc.sections)
        total_rows += rows
        out.append(f"## {doc.kb_id}: {'; '.join(doc.diseases)}\n")
        for s in doc.sections:
            marks = ""
            if s.kind == "overview":
                marks = " [overview]"
            elif s.kind == "otc":
                marks = " [otc]"
            if not s.heading_present:
                marks += " [no heading in source]"
            name = s.path if s.section is not None else f"{s.title} › (overview)"
            out.append(f"- {name} — {s.row_count}{marks}")
        out.append(f"\n{len(doc.sections)} sections, {rows} data rows\n")
    out.append(f"Total: {total_sections} sections, {total_rows} data rows\n")
    return "\n".join(out)
